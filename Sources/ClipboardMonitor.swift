// ClipboardMonitor.swift
// Checks the clipboard twice a second. macOS has no "clipboard changed" notification,
// so every clipboard manager works this way: compare NSPasteboard's changeCount.

import AppKit

@MainActor
final class ClipboardMonitor {
    private weak var store: ClipStore?
    private var lastChangeCount: Int
    private var timer: Timer?

    /// Password managers and other apps mark secret or temporary copies with these types
    /// (see nspasteboard.org). CopyCatch never records them.
    private static let ignoredTypes: [NSPasteboard.PasteboardType] = [
        "org.nspasteboard.ConcealedType",
        "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType",
        "com.agilebits.onepassword",
        "com.apple.is-remote-clipboard.ignore"
    ].map { NSPasteboard.PasteboardType($0) }

    init(store: ClipStore) {
        self.store = store
        self.lastChangeCount = NSPasteboard.general.changeCount
    }

    func start() {
        timer = Timer.scheduledTimer(withTimeInterval: 0.5, repeats: true) { [weak self] _ in
            Task { @MainActor in self?.poll() }
        }
    }

    private func poll() {
        let pasteboard = NSPasteboard.general
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        guard let store else { return }
        if store.suppressNextChange { store.suppressNextChange = false; return }
        if changeCount == store.ownChangeCount { return }                         // our own copy
        guard UserDefaults.standard.bool(forKey: Prefs.monitorClipboard) else { return }

        let types = pasteboard.types ?? []
        if types.contains(where: { Self.ignoredTypes.contains($0) }) { return }

        if let text = pasteboard.string(forType: .string),
           !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty {
            store.add(ClipItem(text: text, source: .clipboard, date: Date()))
        } else if UserDefaults.standard.bool(forKey: Prefs.ocrCopiedImages),
                  let image = NSImage(pasteboard: pasteboard) {
            store.ingestImage(image, source: .clipboard)
        }
    }
}
